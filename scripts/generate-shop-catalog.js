const fs = require("node:fs");
const path = require("node:path");
const { PRODUCTS } = require("../lib/products");

const catalogue = Object.fromEntries(Object.values(PRODUCTS)
  .filter(product => product.kind !== "gift")
  .map(product => [product.productId, {
    n: product.nombre,
    p: product.precioCentimos,
    core: product.kind === "core",
  }]));

fs.writeFileSync(path.join(__dirname, "../shop-catalog.js"),
  `// Generated by node scripts/generate-shop-catalog.js\nwindow.ShopCatalog = ${JSON.stringify(catalogue, null, 2)};\n`);
